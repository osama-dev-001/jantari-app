#!/usr/bin/env node
// Generates the Supabase seed files from the adhkar bundled in the app:
//   supabase/seed/daily_adhkar.csv   — for Table Editor → Import data from CSV
//   supabase/seed/daily_adhkar.sql   — upsert script for the SQL Editor (re-runnable)
// Usage: node scripts/export-adhkar.js
// Uses the app's own row mapping (src/data/adhkar/remote.ts), so the files
// always match what the app expects to download.
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const ts = require('typescript');

const root = path.resolve(__dirname, '..');
const cache = new Map();

/** Minimal loader: transpiles the app's .ts modules to CommonJS and evaluates them. */
function load(file) {
  const full = path.resolve(file);
  if (cache.has(full)) return cache.get(full).exports;
  const source = fs.readFileSync(full, 'utf8');
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true },
  });
  const mod = { exports: {} };
  cache.set(full, mod);
  const localRequire = spec => {
    if (!spec.startsWith('.')) return require(spec);
    const base = path.resolve(path.dirname(full), spec);
    const resolved = [`${base}.ts`, `${base}.tsx`, path.join(base, 'index.ts')].find(f => fs.existsSync(f));
    if (!resolved) throw new Error(`Cannot resolve ${spec} from ${full}`);
    return load(resolved);
  };
  const wrapper = vm.runInThisContext(`(function (exports, require, module) {
${outputText}
})`, { filename: full });
  wrapper(mod.exports, localRequire, mod);
  return mod.exports;
}

const adhkarDir = path.join(root, 'src/data/adhkar');
const { FAVOURITES } = load(path.join(adhkarDir, 'favourites.ts'));
const { OTHERS } = load(path.join(adhkarDir, 'others.ts'));
const { libraryToRows, ROW_COLUMNS } = load(path.join(adhkarDir, 'remote.ts'));

const rows = libraryToRows({ favourites: FAVOURITES, others: OTHERS });

// RFC 4180: every field quoted, quotes doubled, newlines kept inside quotes.
// Null becomes an empty field. UTF-8 without a BOM (a BOM would end up in the
// first column name on import).
const csvField = v => (v === null || v === undefined ? '' : `"${String(v).replace(/"/g, '""')}"`);
const csv = [ROW_COLUMNS.join(','), ...rows.map(r => ROW_COLUMNS.map(c => csvField(r[c])).join(','))].join('\n') + '\n';

const sqlValue = v => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};
const updates = ROW_COLUMNS.filter(c => c !== 'id')
  .map(c => `  ${c} = excluded.${c}`)
  .join(',\n');
const sql = [
  '-- Generated by scripts/export-adhkar.js from the adhkar bundled in the app.',
  '-- Upsert: safe to re-run; existing rows with the same id are updated.',
  `-- ${rows.length} rows.`,
  '',
  `insert into public.daily_adhkar (${ROW_COLUMNS.join(', ')}) values`,
  rows.map(r => `(${ROW_COLUMNS.map(c => sqlValue(r[c])).join(', ')})`).join(',\n'),
  'on conflict (id) do update set',
  `${updates};`,
  '',
].join('\n');

const outDir = path.join(root, 'supabase/seed');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'daily_adhkar.csv'), csv, 'utf8');
fs.writeFileSync(path.join(outDir, 'daily_adhkar.sql'), sql, 'utf8');
console.log(`Wrote ${rows.length} rows (${FAVOURITES.length} favourites, ${OTHERS.length} others) to supabase/seed/`);
